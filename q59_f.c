#define _GNU_SOURCE
#include <signal.h>
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <sys/mman.h>
#include <unistd.h>
static void handler(int sig) { const char msg[] = "Caught SIGSEGV using signal(); exiting safely.\n"; (void)sig; (void)write(STDOUT_FILENO, msg, sizeof(msg)-1); _exit(0); }
int main(void) {
    if (signal(SIGSEGV, handler) == SIG_ERR) { perror("signal"); return 1; }
    puts("About to write to a PROT_NONE mapping to demonstrate SIGSEGV."); fflush(stdout);
    long page_size = sysconf(_SC_PAGESIZE);
    void *page = mmap(NULL, (size_t)page_size, PROT_NONE, MAP_PRIVATE | MAP_ANONYMOUS, -1, 0);
    if (page == MAP_FAILED) { perror("mmap PROT_NONE"); return 1; }
    *(volatile int *)page = 42; /* Deliberate protection fault generated by the kernel. */
    puts("Unexpected: invalid memory write did not fault.");
    return 1;
}
